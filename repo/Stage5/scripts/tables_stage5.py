"""Builds publication-structured tables and results/summary_tables.md from the summary CSVs (no numbers typed by hand)."""
import itertools, numpy as np, pandas as pd
from pathlib import Path
S5 = Path(__file__).resolve().parents[1]; R = S5 / "results"
A = pd.read_csv(R / "per_fold_auc.csv"); F = pd.read_csv(S5 / "qc/folds.csv"); S = pd.read_csv(R / "gene_level_separability.csv")
TASKS = {"ATB_vs_LTB": ["GSE19491", "GSE37250", "GSE73408", "GSE101705", "GSE107994"], "ATB_vs_OD": ["GSE37250", "GSE73408", "GSE42834", "GSE83456"],
         "LTB_vs_CON": ["GSE19439", "GSE19444", "GSE28623", "GSE107994"]}
md = lambda df, idx=False: df.to_markdown(index=idx)
# ---- task difficulty (tidy): one row per task x cohort
rows = []
for task, coh in TASKS.items():
    for c in coh:
        s = S[(S.task == task) & (S.cohort == c) & (S.scope == "all_measured")].iloc[0]; sub = A[(A.task == task) & (A.heldout == c)]
        r = dict(task=task, cohort=c, n_pos=s.n_pos, n_neg=s.n_neg, genes_measured=s.n_genes, pct_genes_AUC_gt_0_8=round(100 * s.prop_AUC_gt_0_8, 2),
                 pct_genes_AUC_lt_0_2=round(100 * s.prop_AUC_lt_0_2, 2), pct_genes_either_dev_gt_0_3=round(100 * s.prop_either_dev_gt_0_3, 2))
        for p in ["Sweeney3", "Zak16", "Native", "Berry86_noTLR7"]:
            for m in ["LR", "DirAvg"]:
                q = sub[(sub.panel == p) & (sub.method == m)].iloc[0]
                r[f"random_median_{m}_n{int(q.n_features)}({p}-matched)" if False else f"rand_med_{m}_{p}"] = q.rand_median
                r[f"curated_{m}_{p}"] = q.AUC
            r[f"size_{p}"] = int(sub[sub.panel == p].n_features.iloc[0])
        rows.append(r)
TD = pd.DataFrame(rows); TD.to_csv(R / "task_difficulty.csv", index=False)
# ---- native stability publication tables
G = pd.read_csv(R / "native_stability_genes.csv"); SM = pd.read_csv(R / "native_stability_summary.csv"); PW = pd.read_csv(R / "native_stability_pairwise.csv")
t1 = []
for _, s in SM.iterrows():
    p = PW[PW.task == s.task]; pools = [int(x.split(":")[1]) for x in s.per_cohort_mRMR_pool_pairwise_overlap.split(";")]
    t1.append({"Task": s.task.replace("_vs_", " vs "), "Folds": s.n_folds, "Genes per fold": s.genes_per_fold, "Distinct genes (all folds)": s.n_distinct_genes,
               "Genes in every fold": s.n_shared_all_folds, "Genes in ≥ half of folds": s.n_in_ge_half_folds, "Genes in one fold only": s.n_selected_once,
               "Pairwise fold overlap, genes (min–max)": f"{p.overlap.min()}–{p.overlap.max()}", "Pairwise Jaccard (min–max)": f"{p.jaccard.min():.2f}–{p.jaccard.max():.2f}",
               "Per-cohort mRMR top-20 pools, pairwise overlap (min–max)": f"{min(pools)}–{max(pools)}",
               "Protein-coding": s.n_protein_coding, "Olfactory receptor": s.n_olfactory_receptor, "microRNA": s.n_microRNA, "Pseudogene": s.n_pseudogene, "lncRNA": s.n_lncRNA})
T1 = pd.DataFrame(t1); T1.to_csv(R / "Table_native_stability_summary.csv", index=False)
t2 = []
for task, coh in TASKS.items():
    g = G[G.task == task]
    for _, r in g.iterrows():
        t2.append({"Task": task.replace("_vs_", " vs "), "Gene": r.gene, **{f"held-out {c}": "●" if r[f"held_{c}"] else "" for c in coh},
                   "Folds selected": f"{r.n_folds_selected}/{r.of_folds}", "HGNC locus type": r.hgnc_locus_type, "Flag": r.flag if isinstance(r.flag, str) else ""})
T2 = pd.DataFrame(t2); T2.to_csv(R / "Table_native_stability_genes.csv", index=False)
# ---- markdown
L = ["# Stage5 summary tables (generated by scripts/tables_stage5.py)", "",
     "Cells: held-out AUC [95% bootstrap CI] · random median (2.5–97.5%) · proportion of 50 size-matched random panels ≥ curated. † overlap from your list; ‡ overlap you accepted in Stage5 (sub-series containment).", "",
     "## Folds", "", md(F), ""]
for task in TASKS:
    for m in ["LR", "RF", "MLP", "MLP_alpha", "singscore", "DirAvg"]:
        s = A[(A.task == task) & (A.method == m)].copy()
        s["cell"] = s.apply(lambda r: f"{r.AUC:.3f} [{r.CI_low:.2f}–{r.CI_high:.2f}]" + ("‡" if r.overlap_added_accepted else ("†" if r.overlap_user_list else "")) +
                            f" · {r.rand_median:.2f} ({r.rand_p2_5:.2f}–{r.rand_p97_5:.2f}) · {r.prop_random_ge_curated:.2f}", axis=1)
        L += [f"## {task} — {m}", "", md(s.pivot(index="heldout", columns="panel", values="cell"), True), ""]
    sh = A[(A.task == task) & (A.method == "LR") & (A.panel == "Native")][["heldout", "heldout_allgene_mean_AUC", "heldout_allgene_mean_CI", "heldout_share_genes_dev_gt_0_2", "heldout_quantile_normalised"]]
    L += [f"## {task} — held-out global shift", "", md(sh), ""]
L += ["## Native panel stability (summary)", "", md(T1), ""]
for task in TASKS: L += [f"## Native genes by fold — {task}", "", md(T2[T2.Task == task.replace('_vs_', ' vs ')].drop(columns="Task").dropna(axis=1, how="all")), ""]
L += ["## Task difficulty (per cohort; random medians are cross-cohort models/scores in the fold holding that cohort out)", "", md(TD), ""]
AL = pd.read_csv(R / "alpha_tuning.csv")
L += ["## Alpha tuning per fold and panel", "", md(AL), ""]
(R / "summary_tables.md").write_text("\n".join(L), encoding="utf-8"); print("ok")
